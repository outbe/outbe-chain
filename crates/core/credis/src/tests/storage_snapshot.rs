//! Snapshot of the CREDIS storage layout. A slot change fails this test until
//! the snapshot file changes on purpose.

use outbe_primitives::storage::dsl::StorageRecord;
use outbe_primitives::storage::layout::{check_snapshot, render_contract, render_record};

use crate::schema::{Credis, CredisContract};

#[test]
fn storage_layout_matches_the_snapshot() {
    let header = "# CREDIS storage layout\n\n\
                  Generated by `src/tests/storage_snapshot.rs`. To update it, run\n\
                  `UPDATE_STORAGE_LAYOUT=1 cargo test -p outbe-credis storage_layout_matches_the_snapshot`.\n\n";
    let tables = [
        render_contract("CredisContract", CredisContract::STORAGE_LAYOUT),
        render_record(
            "Credis",
            <Credis as StorageRecord>::SLOTS,
            Credis::RECORD_LAYOUT,
        ),
    ];
    let rendered = format!("{header}{}", tables.join("\n"));
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("storage-layout.md");
    if let Err(message) = check_snapshot(&path, &rendered) {
        panic!("{message}");
    }
}
