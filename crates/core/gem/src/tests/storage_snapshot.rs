//! Snapshot of the GEM storage layout. A slot change fails this test until
//! the snapshot file changes on purpose.

use outbe_primitives::storage::dsl::StorageRecord;
use outbe_primitives::storage::layout::{check_snapshot, render_contract, render_record};

use crate::schema::{GemContract, GemGroupState, GemItemState};

#[test]
fn storage_layout_matches_the_snapshot() {
    let header = "# GEM storage layout\n\n\
                  Generated by `src/tests/storage_snapshot.rs`. To update it, run\n\
                  `UPDATE_STORAGE_LAYOUT=1 cargo test -p outbe-gem storage_layout_matches_the_snapshot`.\n\n";
    let tables = [
        render_contract("GemContract", GemContract::STORAGE_LAYOUT),
        render_record(
            "GemItemState",
            <GemItemState as StorageRecord>::SLOTS,
            GemItemState::RECORD_LAYOUT,
        ),
        render_record(
            "GemGroupState",
            <GemGroupState as StorageRecord>::SLOTS,
            GemGroupState::RECORD_LAYOUT,
        ),
    ];
    let rendered = format!("{header}{}", tables.join("\n"));
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("storage-layout.md");
    if let Err(message) = check_snapshot(&path, &rendered) {
        panic!("{message}");
    }
}
